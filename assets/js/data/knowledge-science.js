const uniqSc = (list) => [...new Set(list)];
const sid = (grade, kind, ...parts) => `scx-g${grade}-${kind}-${hashString(parts.join('|'))}`;

/**
 * 生成当天的科学参数化题池
 * @param {number} grade 1~6
 * @param {() => number} rng 日期种子随机数
 * @returns {Array} 题目数组
 */
export function scienceGenerated(grade, rng) {
  const facts = SFACT[grade] || [];
  if (!facts.length) return [];
  const groups = SGROUP[grade] || [];
  const funcs = SFUNC[grade] || [];
  const book = SBOOK[grade];

  const out = [];
  const seen = new Set();
  const repeat = (count, build) => {
    for (let i = 0, guard = 0; i < count && guard < count * 12; guard++) {
      const item = build();
      if (item && !seen.has(item.id)) {
        seen.add(item.id);
        out.push(item);
        i++;
      }
    }
  };

  // 1) 科学事实选择（id 按事实内容去重：同一事实一年只出一次选择题）
  repeat(2, () => {
    const [subject, attr, right, wrongs] = pick(rng, facts);
    const options = shuffle(rng, [right, ...wrongs.slice(0, 3)]);
    if (uniqSc(options).length !== 4) return null;
    return {
      id: sid(grade, 'f', subject, attr),
      key: `sc:f:${subject}:${attr}`,
      subject: 'science', grade, level: 1,
      topic: attr, type: 'choice',
      prompt: `${subject}${attr}？`,
      options,
      answer: options.indexOf(right),
      explain: `${subject}${attr}？正确答案是“${right}”。`,
      source: `${book} · 科学探究`
    };
  });

  // 2) 科学事实判断
  repeat(7, () => {
    const [subject, attr, right, wrongs] = pick(rng, facts);
    const truth = rng() < 0.5;
    const said = truth ? right : pick(rng, wrongs);
    if (!said || said === right) return null;
    return {
      id: sid(grade, 'j', subject, attr, said, truth ? '1' : '0'),
      key: `sc:j:${subject}:${attr}`,
      subject: 'science', grade, level: 1,
      topic: attr, type: 'judge',
      prompt: `${subject}${attr}？答案是“${said}”。`,
      answer: truth,
      explain: truth
        ? `说得对，${subject}${attr}？答案是“${right}”。`
        : `说得不对，${subject}${attr}？正确答案是“${right}”，不是“${said}”。`,
      source: `${book} · 科学探究`
    };
  });

  // 3) 分类归属（id 按「成员属于哪一类」去重，同年不再重复考同一条归属）
  repeat(3, () => {
    const [cat, members] = pick(rng, groups);
    const right = pick(rng, members);
    const others = groups.filter((g) => g[0] !== cat);
    // 干扰项必须和正确答案不同，且不能与正确答案重复
    const wrongPool = uniqSc(others.flatMap((g) => g[1])).filter((m) => m !== right);
    const wrong = sample(rng, wrongPool, 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [right, ...wrong]);
    return {
      id: sid(grade, 'in', cat, right),
      key: `sc:in:${cat}`,
      subject: 'science', grade, level: 2,
      topic: '分类', type: 'choice',
      prompt: `下面哪个属于「${cat}」？`,
      options,
      answer: options.indexOf(right),
      explain: `${right}属于「${cat}」。`,
      source: `${book} · 分类`
    };
  });

  // 4) 找不同（id 按题目里的四个成员去重：同一天不会再出同一组）
  repeat(8, () => {
    const [cat, members] = pick(rng, groups);
    const three = sample(rng, members, 3);
    if (three.length < 3) return null;
    const others = groups.filter((g) => g[0] !== cat);
    const odd = pick(rng, pick(rng, others)[1]);
    // 干扰项既不能和正确项重复，也不能本来也属于该类别（避免歧义）
    if (three.includes(odd) || members.includes(odd)) return null;
    const options = shuffle(rng, [...three, odd]);
    return {
      id: sid(grade, 'out', cat, [...three, odd].slice().sort().join('|')),
      key: `sc:out:${cat}`,
      subject: 'science', grade, level: 2,
      topic: '分类', type: 'choice',
      prompt: `下面哪个不属于「${cat}」？`,
      options,
      answer: options.indexOf(odd),
      explain: `其他三个都属于「${cat}」，${odd}不属于。`,
      source: `${book} · 分类`
    };
  });

  // 5) 用途选择（id 按「物体→用途」去重）
  repeat(2, () => {
    const [obj, use] = pick(rng, funcs);
    const wrong = sample(rng, uniqSc(funcs.map((x) => x[1])).filter((x) => x !== use), 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [use, ...wrong]);
    return {
      id: sid(grade, 'fn', obj, use),
      key: `sc:fn:${obj}`,
      subject: 'science', grade, level: 2,
      topic: '用途', type: 'choice',
      prompt: `「${obj}」的主要用途是？`,
      options,
      answer: options.indexOf(use),
      explain: `${obj}可以用来${use}。`,
      source: `${book} · 工具`
    };
  });

  // 6) 用途配对
  repeat(3, () => {
    const four = sample(rng, funcs, 4);
    if (four.length < 4) return null;
    if (new Set(four.map((x) => x[0])).size !== 4) return null;
    const pairs = four.map(([obj, use]) => ({ a: obj, b: use }));
    return {
      id: sid(grade, 'mt', pairs.map((p) => `${p.a}:${p.b}`).sort().join('|')),
      key: `sc:mt:${four.map((x) => x[0]).join('')}`,
      subject: 'science', grade, level: 1,
      topic: '工具配对', type: 'match',
      prompt: '把工具和它的用途配成对',
      pairs,
      explain: pairs.map((p) => `${p.a}可以${p.b}`).join('，') + '。',
      source: `${book} · 工具`
    };
  });

  // 7) 事实配对（高容量基础题：主体与结论配对，左右项均保持简短且唯一）
  repeat(14, () => {
    const four = sample(rng, facts, 4);
    if (four.length < 4) return null;
    const pairs = four.map(([subject, attr, right]) => ({ a: subject, b: right, attr }));
    if (new Set(pairs.map((p) => p.a)).size !== 4) return null;
    if (new Set(pairs.map((p) => p.b)).size !== 4) return null;
    return {
      id: sid(grade, 'fm', pairs.map((p) => `${p.a}:${p.b}`).sort().join('|')),
      key: `sc:fm:${four.map((f) => f[0]).join('')}`,
      subject: 'science', grade, level: 1,
      topic: '事实配对', type: 'match',
      prompt: '把主体和它对应的科学事实配成对',
      pairs: pairs.map(({ a, b }) => ({ a, b })),
      explain: pairs.map((p) => `${p.a}${p.attr}？${p.b}。`).join(''),
      source: `${book} · 科学探究`
    };
  });

  // 8) 分类配对（挑战：为 4 个物体找到所属类别）
  repeat(9, () => {
    const four = sample(rng, groups, 4);
    if (four.length < 4) return null;
    const pairs = four.map(([cat, members]) => ({ a: pick(rng, members), b: cat }));
    if (new Set(pairs.map((p) => p.a)).size !== 4) return null;
    if (new Set(pairs.map((p) => p.b)).size !== 4) return null;
    return {
      id: sid(grade, 'gp', pairs.map((p) => `${p.a}:${p.b}`).sort().join('|')),
      key: `sc:gp:${four.map((g) => g[0]).join('')}`,
      subject: 'science', grade, level: 2,
      topic: '分类配对', type: 'match',
      prompt: '把下面的物体和它所属的类别配成对',
      pairs,
      explain: pairs.map((p) => `${p.a}属于「${p.b}」。`).join(''),
      source: `${book} · 分类`
    };
  });

  return out;
}

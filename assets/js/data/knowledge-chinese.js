const ZH_RADICALS = ['氵', '木', '扌', '艹', '口', '日', '月', '女', '亻', '纟', '土', '火', '石', '虫', '鸟', '雨', '目', '足', '竹', '心', '宀', '辶', '王', '马', '禾', '米', '饣', '衣', '酉', '贝'];

const uniqStr = (list) => [...new Set(list)];

const zid = (grade, kind, ...parts) => `zhx-g${grade}-${kind}-${hashString(parts.join('|'))}`;

/**
 * 生成当天的语文参数化题池
 * @param {number} grade 1~6
 * @param {() => number} rng 日期种子随机数
 * @returns {Array} 题目数组
 */
export function chineseGenerated(grade, rng) {
  const chars = ZCHARS[grade] || [];
  if (!chars.length) return [];
  const syn = ZSYN[grade] || [];
  const ant = ZANT[grade] || [];
  const mw = ZMW[grade] || [];
  const idiom = ZIDIOM[grade] || [];
  const poem = ZPOEM[grade] || [];
  const book = ZBOOK[grade];

  const out = [];
  const seen = new Set();
  const repeat = (count, build) => {
    for (let i = 0, guard = 0; i < count && guard < count * 12; guard++) {
      const item = build();
      if (item && !seen.has(item.id)) {
        seen.add(item.id);
        out.push(item);
        i++;
      }
    }
  };
  const pickChar = (used) => {
    const list = chars.filter((row) => !used.has(row[0]));
    if (!list.length) return null;
    const row = pick(rng, list);
    used.add(row[0]);
    return row;
  };
  const usedPy = new Set();
  const usedZp = new Set();
  const usedWd = new Set();
  const usedBw = new Set();

  // 1) 选读音
  repeat(7, () => {
    const row = pickChar(usedPy);
    if (!row) return null;
    const [zi, py] = row;
    const distract = uniqStr(chars.filter((x) => x[1] !== py).map((x) => x[1]));
    const wrong = sample(rng, distract, 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [py, ...wrong]);
    return {
      id: zid(grade, 'py', zi, options.join('|')),
      key: `zh:py:${zi}`,
      subject: 'chinese', grade, level: 1,
      topic: '字音', type: 'choice',
      prompt: `“${zi}”的正确读音是？`,
      options,
      answer: options.indexOf(py),
      explain: `“${zi}”读 ${py}，可以组词“${row[2]}”。`,
      source: `${book} · 识字`
    };
  });

  // 2) 看拼音选字
  repeat(6, () => {
    const row = pickChar(usedZp);
    if (!row) return null;
    const [zi, py] = row;
    const others = sample(rng, chars.filter((x) => x[0] !== zi), 3).map((x) => x[0]);
    if (others.length < 3) return null;
    const options = shuffle(rng, [zi, ...others]);
    return {
      id: zid(grade, 'zp', py, options.join('|')),
      key: `zh:zp:${zi}`,
      subject: 'chinese', grade, level: 2,
      topic: '字音', type: 'choice',
      prompt: `读音是“${py}”的字是下面哪一个？`,
      options,
      answer: options.indexOf(zi),
      explain: `读 ${py} 的是“${zi}”，可以组词“${row[2]}”。`,
      source: `${book} · 识字`
    };
  });

  // 3) 字音判断
  repeat(5, () => {
    const row = pick(rng, chars);
    const [zi, py] = row;
    const truth = rng() < 0.5;
    const other = pick(rng, uniqStr(chars.filter((x) => x[1] !== py).map((x) => x[1])));
    if (!other) return null;
    const said = truth ? py : other;
    return {
      id: zid(grade, 'pyj', zi, said, truth ? '1' : '0'),
      key: `zh:pyj:${zi}`,
      subject: 'chinese', grade, level: grade <= 2 ? 1 : 2,
      topic: '字音', type: 'judge',
      prompt: `“${zi}”读作 ${said}。`,
      answer: truth,
      explain: `“${zi}”读 ${py}${truth ? '，这句话是对的。' : `，不是 ${said}。`}`,
      source: `${book} · 识字`
    };
  });

  // 4) 组词（找出含有这个字的词语）
  repeat(5, () => {
    const row = pickChar(usedWd);
    if (!row) return null;
    const [zi] = row;
    const okWords = chars.filter((x) => x[2].includes(zi) && x[0] === zi).map((x) => x[2]);
    const word = okWords[0] || row[2];
    const others = uniqStr(chars.filter((x) => x[0] !== zi && !x[2].includes(zi)).map((x) => x[2]));
    const wrong = sample(rng, others, 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [word, ...wrong]);
    return {
      id: zid(grade, 'wd', zi, options.join('|')),
      key: `zh:wd:${zi}`,
      subject: 'chinese', grade, level: 1,
      topic: '组词', type: 'choice',
      prompt: `下面哪个词语中包含“${zi}”字？`,
      options,
      answer: options.indexOf(word),
      explain: `“${word}”中含有“${zi}”字。`,
      source: `${book} · 识字`
    };
  });

  // 5) 偏旁
  repeat(4, () => {
    const row = pickChar(usedBw);
    if (!row) return null;
    const [zi, , , bw] = row;
    const wrong = sample(rng, ZH_RADICALS.filter((x) => x !== bw), 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [bw, ...wrong]);
    return {
      id: zid(grade, 'bw', zi, options.join('|')),
      key: `zh:bw:${zi}`,
      subject: 'chinese', grade, level: 2,
      topic: '偏旁', type: 'choice',
      prompt: `“${zi}”的偏旁是什么？`,
      options,
      answer: options.indexOf(bw),
      explain: `“${zi}”的偏旁是“${bw}”。`,
      source: `${book} · 识字`
    };
  });

  // 6) 近义词
  repeat(4, () => {
    const item = pick(rng, syn);
    if (!item) return null;
    const [word, near] = item;
    const wrong = sample(rng, uniqStr(syn.filter((x) => x[0] !== word && x[1] !== near).map((x) => x[1])), 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [near, ...wrong]);
    return {
      id: zid(grade, 'sy', word, options.join('|')),
      key: `zh:sy:${word}`,
      subject: 'chinese', grade, level: 2,
      topic: '近义词', type: 'choice',
      prompt: `与“${word}”意思相近的词语是？`,
      options,
      answer: options.indexOf(near),
      explain: `“${word}”和“${near}”意思相近。`,
      source: `${book} · 词语`
    };
  });

  // 7) 反义词
  repeat(4, () => {
    const item = pick(rng, ant);
    if (!item) return null;
    const [word, opp] = item;
    const wrong = sample(rng, uniqStr(ant.filter((x) => x[0] !== word && x[1] !== opp).map((x) => x[1])), 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [opp, ...wrong]);
    return {
      id: zid(grade, 'fy', word, options.join('|')),
      key: `zh:fy:${word}`,
      subject: 'chinese', grade, level: grade <= 2 ? 1 : 2,
      topic: '反义词', type: 'choice',
      prompt: `“${word}”的反义词是？`,
      options,
      answer: options.indexOf(opp),
      explain: `“${word}”和“${opp}”意思相反。`,
      source: `${book} · 词语`
    };
  });

  // 8) 量词
  repeat(4, () => {
    const item = pick(rng, mw);
    if (!item) return null;
    const [noun, liang] = item;
    const wrong = sample(rng, uniqStr(mw.map((x) => x[1]).concat(['只', '条', '张', '把', '片'])).filter((x) => x !== liang), 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [liang, ...wrong]);
    return {
      id: zid(grade, 'lc', noun, options.join('|')),
      key: `zh:lc:${noun}`,
      subject: 'chinese', grade, level: 1,
      topic: '量词', type: 'choice',
      prompt: `一（  ）${noun}，括号里应该填什么？`,
      options,
      answer: options.indexOf(liang),
      explain: `${noun}用“${liang}”：一${liang}${noun}。`,
      source: `${book} · 词语`
    };
  });

  // 9) 成语补字
  repeat(3, () => {
    const item = pick(rng, idiom);
    if (!item) return null;
    const [word, pos, meaning] = item;
    if (pos < 0 || pos >= word.length) return null;
    const right = word[pos];
    const masked = word.slice(0, pos) + '□' + word.slice(pos + 1);
    const pool = uniqStr(idiom.map((x) => x[0]).join('').split('')).filter((ch) => ch !== right);
    const wrong = sample(rng, pool, 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [right, ...wrong]);
    return {
      id: zid(grade, 'cy', masked, options.join('|')),
      key: `zh:cy:${word}`,
      subject: 'chinese', grade, level: 2,
      topic: '成语', type: 'choice',
      prompt: `成语“${masked}”中缺少的字是？`,
      options,
      answer: options.indexOf(right),
      explain: `完整成语是“${word}”，意思是${meaning}。`,
      source: `${book} · 成语`
    };
  });

  // 10) 古诗接句
  repeat(3, () => {
    const item = pick(rng, poem);
    if (!item) return null;
    const [first, second] = item;
    const wrong = sample(rng, uniqStr(poem.map((x) => x[1])).filter((x) => x !== second), 3);
    if (wrong.length < 3) return null;
    const options = shuffle(rng, [second, ...wrong]);
    return {
      id: zid(grade, 'gj', first, options.join('|')),
      key: `zh:gj:${first}`,
      subject: 'chinese', grade, level: 2,
      topic: '古诗', type: 'choice',
      prompt: `“${first}”的下一句是？`,
      options,
      answer: options.indexOf(second),
      explain: `${item[2]}：“${first}，${second}。”`,
      source: `${book} · 古诗`
    };
  });

  // 11) 字音配对
  repeat(3, () => {
    const four = sample(rng, chars, 4);
    if (four.length < 4) return null;
    if (new Set(four.map((x) => x[1])).size !== 4) return null;
    const pairs = four.map((x) => ({ a: x[0], b: x[1] }));
    return {
      id: zid(grade, 'pm', pairs.map((p) => `${p.a}:${p.b}`).join('|')),
      key: `zh:pm:${four.map((x) => x[0]).join('')}`,
      subject: 'chinese', grade, level: 1,
      topic: '字音配对', type: 'match',
      prompt: '把汉字和它的读音配成对',
      pairs,
      explain: pairs.map((p) => `${p.a}读 ${p.b}`).join('，') + '。',
      source: `${book} · 识字`
    };
  });

  /* —— 以下为难度加深题型 —— */

  // 12) 整体认读音节辨析（一、二年级挑战）
  const YNR = ['zhi', 'chi', 'shi', 'ri', 'zi', 'ci', 'si', 'yi', 'wu', 'yu', 'ye', 'yue', 'yuan', 'yin', 'yun', 'ying'];
  const NOT_YNR = ['zh', 'ch', 'sh', 'r', 'z', 'c', 's', 'y', 'w', 'ge', 'ka', 'ma', 'ba', 'po', 'lu', 'de', 'ta'];
  if (grade <= 2) {
    repeat(3, () => {
      const forward = rng() < 0.5;
      if (forward) {
        const right = pick(rng, YNR);
        const wrong = sample(rng, NOT_YNR, 3);
        const options = shuffle(rng, [right, ...wrong]);
        return {
          id: zid(grade, 'ynr', right, options.join('|')),
          key: `zh:ynr:${right}`,
          subject: 'chinese', grade, level: 2,
          topic: '整体认读音节', type: 'choice',
          prompt: '下面哪一个是整体认读音节？',
          options,
          answer: options.indexOf(right),
          explain: `“${right}”是整体认读音节，要整体认读，不能拼读。`,
          source: `${book} · 拼音`
        };
      }
      const right = pick(rng, NOT_YNR);
      const wrong = sample(rng, YNR, 3);
      const options = shuffle(rng, [right, ...wrong]);
      return {
        id: zid(grade, 'ynr', right, options.join('|')),
        key: `zh:ynr:not:${right}`,
        subject: 'chinese', grade, level: 2,
        topic: '整体认读音节', type: 'choice',
        prompt: '下面哪一个不是整体认读音节？',
        options,
        answer: options.indexOf(right),
        explain: `“${right}”不是整体认读音节；${wrong.join('、')} 都是整体认读音节。`,
        source: `${book} · 拼音`
      };
    });
  }

  // 13) 成语意思填空（按意思选成语，挑战）
  if (idiom.length >= 4) {
    repeat(3, () => {
      const item = pick(rng, idiom);
      if (!item) return null;
      const [word, , meaning] = item;
      const others = sample(rng, idiom.filter((x) => x[0] !== word && x[2] !== meaning), 3).map((x) => x[0]);
      if (others.length < 3) return null;
      const options = shuffle(rng, [word, ...others]);
      return {
        id: zid(grade, 'cy2', word, options.join('|')),
        key: `zh:cy2:${word}`,
        subject: 'chinese', grade, level: 2,
        topic: '成语理解', type: 'choice',
        prompt: `表示“${meaning}”的成语是哪一个？`,
        options,
        answer: options.indexOf(word),
        explain: `“${word}”的意思是${meaning}。`,
        source: `${book} · 成语`
      };
    });
  }

  // 14) 诗句理解（三~六年级挑战：哪句诗与主题有关）
  const POEM_SCENE = [
    ['碧玉妆成一树高，万条垂下绿丝绦。', '春天'],
    ['小荷才露尖尖角，早有蜻蜓立上头。', '夏天'],
    ['停车坐爱枫林晚，霜叶红于二月花。', '秋天'],
    ['墙角数枝梅，凌寒独自开。', '冬天'],
    ['清明时节雨纷纷，路上行人欲断魂。', '清明节'],
    ['爆竹声中一岁除，春风送暖入屠苏。', '春节'],
    ['独在异乡为异客，每逢佳节倍思亲。', '思念家乡'],
    ['举头望明月，低头思故乡。', '思念家乡'],
    ['谁知盘中餐，粒粒皆辛苦。', '珍惜粮食'],
    ['少壮不努力，老大徒伤悲。', '珍惜时间'],
    ['欲穷千里目，更上一层楼。', '登高望远'],
    ['春眠不觉晓，处处闻啼鸟。', '春天']
  ];
  if (grade >= 3) {
    repeat(3, () => {
      const item = pick(rng, POEM_SCENE);
      const wrong = sample(rng, POEM_SCENE.filter((x) => x[0] !== item[0] && x[1] !== item[1]), 3);
      if (wrong.length < 3) return null;
      const options = shuffle(rng, [item[0], ...wrong.map((x) => x[0])]);
      return {
        id: zid(grade, 'pj', item[1], options.join('|')),
        key: `zh:pj:${item[1]}`,
        subject: 'chinese', grade, level: 2,
        topic: '诗句理解', type: 'choice',
        prompt: `下面哪句诗和“${item[1]}”有关？`,
        options,
        answer: options.indexOf(item[0]),
        explain: `“${item[0]}”与“${item[1]}”有关。`,
        source: '日积月累 · 古诗理解'
      };
    });
  }

  return out;
}

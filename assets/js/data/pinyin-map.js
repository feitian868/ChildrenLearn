/**
 * 把一段字符串里的汉字替换为 <ruby>字<rt>pīn yīn</rt></ruby>。
 * 非汉字（拼音字母、标点、数字、选项分隔符等）原样保留。
 * 多音字简单覆盖：若同一字在题干和选项里读音不同，用最常见读法即可（一年级多数字只有一种读法）。
 */
/** 带声调的拼音字母集合（用于识别原生拼音串） */
const PINYIN_LETTERS = /^[a-zA-Zā-ǖĀ-Ǖ]+$/u;

export function pinyinize(text) {
  if (!text) return '';
  let out = '';
  let pyBuf = '';            // 累计连续的拼音字母串
  function flushPyBuf() {
    if (!pyBuf) return;
    // 2 个及以上连续拼音字母 → 用 span 包起来加字母间距
    if (pyBuf.length >= 2) out += `<span class="pinyin-literal">${pyBuf}</span>`;
    else out += pyBuf;
    pyBuf = '';
  }
  for (const ch of String(text)) {
    // 先看是不是拼音字母（包括 āéīōūǖ 等带声调）
    if (PINYIN_LETTERS.test(ch)) {
      pyBuf += ch;
      continue;
    }
    // 不是拼音字母，先把 buf 刷掉
    flushPyBuf();
    // 汉字 → 加 <ruby>
    if (PINYIN[ch]) {
      const py = PINYIN[ch];
      out += `<ruby>${ch}<rt>${py}</rt></ruby>`;
    } else {
      out += ch;
    }
  }
  flushPyBuf();
  return out;
}

/**
 * 判断一道题是否需要自动加拼音：
 *   1) 必须是一年级（grade === 1）；
 *   2) 已经是拼音字母的内容（如声调题的 mā、má），pinyinize 会原样保留；
 *   3) 其他年级一律不加（二三年级以上逐步脱离拼音辅助）。
 */
export function needsPinyin(grade) {
  return Number(grade) === 1;
}
